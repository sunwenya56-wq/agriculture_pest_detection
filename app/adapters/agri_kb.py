def normalize_name(name: str) -> str:
    name = name.strip()
    if name in EN_TO_ZH:
        return EN_TO_ZH[name]
    for zh in KNOWLEDGE_BASE:
        if zh in name:
            return zh
    return name


def fallback_advice(pest_names: list[str]) -> str:
    """生成结构化兜底建议，保证任何情况下都有可读输出。"""
    if not pest_names:
        return "未检测到害虫，无需防治。"

    sections: list[str] = []
    for raw in pest_names:
        zh = normalize_name(raw)
        entry = KNOWLEDGE_BASE.get(zh)
        if entry:
            lines = [f"## {zh}"]
            for dimension, items in entry.items():
                lines.append(f"- {dimension}：" + "；".join(items))
            sections.append("\n".join(lines))
        else:
            sections.append(
                f"## {raw}\n- 农业防治：清除残株与杂草，减少虫源\n"
                "- 物理防治：灯光或粘板诱杀\n"
                "- 化学防治：轮换使用登记药剂，注意安全间隔期"
            )

    sections.append(
        "## 通用建议\n"
        "- 优先采用农业防治、物理防治和生物防治\n"
        "- 化学防治需轮换作用机理，避免抗药性\n"
        "- 记录发生时间与密度，建立田间监测档案"
    )
    return "\n\n".join(sections)
